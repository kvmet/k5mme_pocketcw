//! Rasterizes a monospace TTF into the firmware's 4-bit antialiased glyph tables.
//! Usage: cargo run --release -- <font.ttf> <output.rs>

use std::{env, fmt::Write as _, fs, process::ExitCode};

struct Spec {
    name: &'static str,
    px: f32,
    /// Cell width and height in pixels; `None` sizes the cell from the font metrics.
    cell: Option<(usize, usize)>,
    /// Sorted by byte value: the firmware finds glyphs by binary search.
    chars: &'static str,
}

const ASCII: &str = " !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`abcdefghijklmnopqrstuvwxyz{|}~";

/// ASCII without a..z. `Font::draw` shows a missing lowercase letter as its capital.
const ASCII_UPPER: &str = " !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`{|}~";

const SPECS: &[Spec] = &[
    // 32 x 15 text grid on the 320 x 240 screen.
    Spec { name: "SMALL", px: 13.0, cell: Some((10, 16)), chars: ASCII },
    // Labels, units and axes: all capitals.
    Spec { name: "TINY", px: 10.0, cell: Some((7, 12)), chars: ASCII_UPPER },
];

const HEADER: &str = "// Generated by tools/fontgen from B612 Mono Regular, SIL Open Font License 1.1 (see B612-OFL.txt).\n\
// Regenerate with the tool; hand edits are lost.\n\nuse crate::font::Font;\n";

fn main() -> ExitCode {
    let args: Vec<String> = env::args().collect();
    let [_, ttf, out] = args.as_slice() else {
        eprintln!("usage: fontgen <font.ttf> <output.rs>");
        return ExitCode::FAILURE;
    };
    let data = match fs::read(ttf) {
        Ok(data) => data,
        Err(e) => {
            eprintln!("{ttf}: {e}");
            return ExitCode::FAILURE;
        }
    };
    let font = match fontdue::Font::from_bytes(data, fontdue::FontSettings::default()) {
        Ok(font) => font,
        Err(e) => {
            eprintln!("{ttf}: {e}");
            return ExitCode::FAILURE;
        }
    };

    let mut rs = String::from(HEADER);
    let mut clipped_total = 0;
    for spec in SPECS {
        clipped_total += emit(&font, spec, &mut rs);
    }
    if clipped_total > 0 {
        eprintln!("{clipped_total} visible pixels fall outside their cells; nothing written");
        return ExitCode::FAILURE;
    }
    if let Err(e) = fs::write(out, rs) {
        eprintln!("{out}: {e}");
        return ExitCode::FAILURE;
    }
    ExitCode::SUCCESS
}

/// Appends one `Font` static to `rs`. Returns the number of visible pixels clipped by the cell.
fn emit(font: &fontdue::Font, spec: &Spec, rs: &mut String) -> usize {
    assert!(spec.chars.as_bytes().is_sorted(), "{}: chars must be sorted", spec.name);
    let advance = font.metrics('0', spec.px).advance_width;
    // Ink extents of all of ASCII, in pixels above the baseline; tighter than the line metrics.
    // A font with fewer glyphs keeps the baseline it would have with all of them.
    let ink_top = ASCII.chars().map(|c| font.metrics(c, spec.px)).map(|m| m.ymin + m.height as i32).max().unwrap_or(0);
    let ink_bottom = ASCII.chars().map(|c| font.metrics(c, spec.px).ymin).min().unwrap_or(0);
    let ink_height = (ink_top - ink_bottom) as usize;
    let (width, height) = spec.cell.unwrap_or((advance.ceil() as usize, ink_height));
    let baseline = (height as i32 - ink_height as i32) / 2 + ink_top;
    eprintln!(
        "{}: {}px, cell {width}x{height}, advance {advance:.2}, ink {ink_bottom}..{ink_top}",
        spec.name, spec.px
    );

    let mut pixels = Vec::new();
    let mut boxes = Vec::new();
    let mut offsets = Vec::new();
    let mut clipped = 0;
    for ch in spec.chars.chars() {
        let (m, bitmap) = font.rasterize(ch, spec.px);
        let left = ((width as f32 - m.advance_width) / 2.0).round() as i32 + m.xmin;
        let top = baseline - m.ymin - m.height as i32;
        let mut cell = vec![0u8; width * height];
        for by in 0..m.height {
            for bx in 0..m.width {
                let level = ((bitmap[by * m.width + bx] as u32 * 15 + 127) / 255) as u8;
                let (x, y) = (left + bx as i32, top + by as i32);
                if x < 0 || y < 0 || x >= width as i32 || y >= height as i32 {
                    if level > 0 {
                        clipped += 1;
                    }
                    continue;
                }
                cell[y as usize * width + x as usize] = level;
            }
        }
        let ink = ink_box(&cell, width, height);
        let [x0, y0, w, h] = ink.map(usize::from);
        let cropped: Vec<u8> = (y0..y0 + h).flat_map(|y| (x0..x0 + w).map(move |x| (x, y))).map(|(x, y)| cell[y * width + x]).collect();
        assert_eq!(uncrop(&cropped, ink, width, height), cell, "{}: {ch:?} crops wrong", spec.name);
        offsets.push(pixels.len());
        for pair in cropped.chunks(2) {
            pixels.push(pair[0] << 4 | pair.get(1).copied().unwrap_or(0));
        }
        boxes.push(ink);
    }
    offsets.push(pixels.len());
    assert!(pixels.len() <= u16::MAX as usize, "{}: offsets overflow u16", spec.name);
    if clipped > 0 {
        eprintln!("{}: {clipped} visible pixels clipped", spec.name);
    }

    let _ = write!(
        rs,
        "\npub static {}: Font = Font {{\n    width: {width},\n    height: {height},\n    chars: b{:?},\n    boxes: &[",
        spec.name, spec.chars
    );
    for (i, b) in boxes.iter().enumerate() {
        let _ = write!(rs, "{}[{}, {}, {}, {}],", if i % 8 == 0 { "\n        " } else { " " }, b[0], b[1], b[2], b[3]);
    }
    rs.push_str("\n    ],\n    offsets: &[");
    for (i, o) in offsets.iter().enumerate() {
        let _ = write!(rs, "{}{o},", if i % 16 == 0 { "\n        " } else { " " });
    }
    rs.push_str("\n    ],\n    pixels: &[");
    for (i, byte) in pixels.iter().enumerate() {
        let _ = write!(rs, "{}0x{byte:02X},", if i % 16 == 0 { "\n        " } else { " " });
    }
    rs.push_str("\n    ],\n};\n");
    clipped
}

/// Left, top, width and height of the nonzero pixels in a `width` by `height` cell; all 0 for
/// an empty cell.
fn ink_box(cell: &[u8], width: usize, height: usize) -> [u8; 4] {
    let inked = |x: usize, y: usize| cell[y * width + x] > 0;
    let rows: Vec<usize> = (0..height).filter(|&y| (0..width).any(|x| inked(x, y))).collect();
    let cols: Vec<usize> = (0..width).filter(|&x| (0..height).any(|y| inked(x, y))).collect();
    match (rows.first(), rows.last(), cols.first(), cols.last()) {
        (Some(&y0), Some(&y1), Some(&x0), Some(&x1)) => [x0, y0, x1 - x0 + 1, y1 - y0 + 1].map(|v| v as u8),
        _ => [0; 4],
    }
}

/// The full cell back from a box's pixels, as `Font::draw` reads them.
fn uncrop(cropped: &[u8], [x0, y0, w, h]: [u8; 4], width: usize, height: usize) -> Vec<u8> {
    let [x0, y0, w, h] = [x0, y0, w, h].map(usize::from);
    let mut cell = vec![0u8; width * height];
    for y in 0..h {
        for x in 0..w {
            cell[(y0 + y) * width + x0 + x] = cropped[y * w + x];
        }
    }
    cell
}
